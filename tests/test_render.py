"""The generated blocks: what they render, their order, and how they are spliced into README.md and done.md."""

from __future__ import annotations

import datetime
from pathlib import Path

import pytest
from conftest import FIXTURES, closed_meta, item_text, make_roadmap, open_meta, roadmap


def test_the_committed_fixture_is_what_the_renderer_produces() -> None:
    """The fixture's README.md and done.md are the golden files. To regenerate
    them, run `python scripts/roadmap.py index --dir tests/fixtures/valid/roadmap`."""
    rm = roadmap.open_roadmap(FIXTURES / "valid" / "roadmap")

    assert roadmap.check(rm) == []


def test_empty_blocks_say_so() -> None:
    assert "*Empty.*" in roadmap.render_done([])
    assert roadmap.render_index([]).count("*Empty.*") == 3


def test_index_orders_by_bucket_then_rank_and_shows_the_note(tmp_path: Path) -> None:
    rm = make_roadmap(
        tmp_path,
        {
            "items/b.md": item_text(open_meta(id="b", title="B", rank=2, gate="fast enough")),
            "items/a.md": item_text(open_meta(id="a", title="A", bucket="later", blocked_on="a call")),
            "items/c.md": item_text(open_meta(id="c", title="C", rank=1)),
        },
    )
    items, _, _ = roadmap.load(rm)

    block = roadmap.render_index(items)

    assert block.index("[C]") < block.index("[B]") < block.index("[A]")
    assert "**Gate:** fast enough" in block
    assert "**Blocked on:** a call" in block


def test_done_is_newest_first_and_grouped_by_month(tmp_path: Path) -> None:
    rm = make_roadmap(
        tmp_path,
        {
            "archive/old.md": item_text(closed_meta(id="old", title="Old", closed=datetime.date(2026, 7, 1))),
            "archive/new.md": item_text(
                closed_meta(id="new", title="New", closed=datetime.date(2026, 9, 20), shipped_as="pr-9")
            ),
            "archive/mid.md": item_text(
                closed_meta(id="mid", title="Mid", closed=datetime.date(2026, 9, 2), outcome="declined")
            ),
        },
    )
    _, archived, _ = roadmap.load(rm)

    block = roadmap.render_done(archived)

    assert block.index("### 2026-09 (2)") < block.index("[New]") < block.index("[Mid]") < block.index("### 2026-07 (1)")
    assert "- **shipped** [New](archive/new.md) — closed 2026-09-20 as `pr-9`" in block
    assert "- **declined** [Mid](archive/mid.md) — closed 2026-09-02" in block


def test_splice_keeps_the_prose_around_the_block() -> None:
    text = f"before\n{roadmap.INDEX_BEGIN}\nold\n{roadmap.INDEX_END}\nafter\n"

    spliced = roadmap.splice(text, roadmap.INDEX_BEGIN, roadmap.INDEX_END, "NEW", Path("README.md"))

    assert spliced == "before\nNEW\nafter\n"


def test_splice_accepts_an_older_marker_wording() -> None:
    """snakestream's marker names a different script. Adopting the skill should
    need an `index` run, not a hand edit."""
    text = (
        "<!-- BEGIN INDEX: generated by tools/roadmap_index.py; edit roadmap/items/*.md instead -->\n"
        "x\n"
        "<!-- END INDEX -->"
    )

    spliced = roadmap.splice(text, roadmap.INDEX_BEGIN, roadmap.INDEX_END, "NEW", Path("README.md"))

    assert spliced == "NEW"


def test_splice_refuses_a_file_without_markers() -> None:
    with pytest.raises(roadmap.UsageError, match="markers not found"):
        roadmap.splice("# Roadmap\n", roadmap.INDEX_BEGIN, roadmap.INDEX_END, "NEW", Path("README.md"))


def test_index_names_dependencies_open_closed_and_unknown(tmp_path: Path) -> None:
    rm = make_roadmap(
        tmp_path,
        {
            "items/a.md": item_text(open_meta(id="a", title="A")),
            "items/b.md": item_text(open_meta(id="b", title="B", rank=2, gate="fast", depends_on=["a", "old", "gone"])),
            "archive/old.md": item_text(closed_meta(id="old", title="Old")),
        },
    )
    items, archived, _ = roadmap.load(rm)

    block = roadmap.render_index(items, archived)

    assert (
        "2. [B](items/b.md) — filed 2026-09-06<br>  **Gate:** fast"
        "<br>  **Depends on:** [A](items/a.md), [Old](archive/old.md) (shipped), gone"
    ) in block
