/** Read roadmap.toml if there is one. `files` is always a ref kind, meaning
 * a path relative to the root. Any other kind must be declared. */
export function openRoadmap(directory: string): Roadmap {
  const dir = join(directory);
  const configPath = join(dir, "roadmap.toml");
  let config: Meta = {};
  if (existsSync(configPath)) {
    try {
      config = fromToml(parseToml(readText(configPath), { integersAsBigInt: true })) as Meta;
    } catch (exc) {
      if (!(exc instanceof TomlError)) throw exc;
      throw new ConfigError(`${configPath}: malformed TOML: ${tomlReason(exc)} [config]`);
    }
  }
  const unknown = Object.keys(config).filter((k) => !["root", "refs", "milestones"].includes(k));
  if (unknown.length) throw new ConfigError(`${configPath}: unknown key(s) ${unknown.sort().join(", ")} [config]`);
  const root = "root" in config ? config.root : "..";
  if (typeof root !== "string") throw new ConfigError(`${configPath}: root must be a path string [config]`);
  const refs = "refs" in config ? config.refs : {};
  if (!isDict(refs)) throw new ConfigError(`${configPath}: refs must be a table of path templates [config]`);

  const kinds = new Map<string, readonly string[]>([["files", ["{}"]]]);
  for (const [kind, value] of Object.entries(refs)) {
    const templates = typeof value === "string" ? [value] : value;
    if (
      !(
        Array.isArray(templates) &&
        templates.length &&
        templates.every((t) => typeof t === "string" && t.includes("{}"))
      )
    ) {
      throw new ConfigError(
        `${configPath}: refs.${kind} must be a path template containing {}, or a list of them [config]`,
      );
    }
    kinds.set(kind, templates as string[]);
  }
  const rootPath = normpath(join(dir, root));
  return new Roadmap(dir, rootPath, kinds, milestonesOf(config, configPath));
}

/** The [milestones] table: a kebab-case id per milestone, each with a title
 * and a bare TOML date. */
function milestonesOf(config: Meta, configPath: string): Map<string, Milestone> {
  const table = "milestones" in config ? config.milestones : {};
  if (!isDict(table)) {
    throw new ConfigError(
      `${configPath}: milestones must be a table, e.g. beta = { title = "...", date = ... } [config]`,
    );
  }
  const milestones = new Map<string, Milestone>();
  for (const [mid, spec] of Object.entries(table)) {
    if (!SLUG.test(mid))
      throw new ConfigError(`${configPath}: milestone id ${repr(mid)} is not a kebab-case slug [config]`);
    const keys = isDict(spec) ? Object.keys(spec).sort() : [];
    const title = isDict(spec) ? spec.title : undefined;
    const date = isDict(spec) ? spec.date : undefined;
    if (keys.join() !== "date,title" || !(typeof title === "string" && title.trim() && date instanceof Day)) {
      throw new ConfigError(
        `${configPath}: milestones.${mid} must be { title = "...", date = 2026-12-01 }, with a bare TOML date [config]`,
      );
    }
    milestones.set(mid, new Milestone(mid, title, date));
  }
  return milestones;
}

/** A parse error in one line, the way tomllib words it: what went wrong, then where. */
export function tomlReason(exc: TomlError): string {
  const what = exc.message.split("\n")[0]?.replace(/^Invalid TOML document: /, "") ?? exc.message;
  return `${what[0]?.toUpperCase() ?? ""}${what.slice(1)} (at line ${exc.line}, column ${exc.column})`;
}

export function parseTomlMeta(text: string): Meta {
  return fromToml(parseToml(text, { integersAsBigInt: true })) as Meta;
}

/** Split one item file into its metadata and its prose. Given `text`, parse
 * that as the file's contents instead of reading it. Throws
 * FrontmatterError, with the path in the message, on anything the TOML
 * parser or the fence rejects. */
export function parse(path: string, archived = false, text?: string): Item {
  const match = FRONTMATTER.exec(text ?? readText(path));
  if (match === null) throw new FrontmatterError(path, "no +++-fenced TOML frontmatter at the top of the file");
  let meta: Meta;
  try {
    meta = parseTomlMeta(match[1] ?? "");
  } catch (exc) {
    if (!(exc instanceof TomlError)) throw exc;
    throw new FrontmatterError(path, `malformed TOML frontmatter: ${tomlReason(exc)}`);
  }
  return new Item(path, meta, match[2] ?? "", archived);
}

/** Every open item, in index order (by bucket, then rank). Every archived
 * item, in done.md order (newest first). And every file that would not parse,
 * as problems, so one broken file doesn't hide the rest. */
export function load(rm: Roadmap): [Item[], Item[], Problem[]] {
  const [items, problems] = loadDir(rm.itemsDir, false);
  const [archived, more] = loadDir(rm.archiveDir, true);
  const order = (i: Item) => {
    const index = BUCKETS.indexOf(i.bucket as Bucket);
    return index === -1 ? BUCKETS.length : index;
  };
  items.sort((a, b) => cmp([order(a), a.rank, a.id], [order(b), b.rank, b.id]));
  archived.sort((a, b) => cmp([a.id], [b.id]));
  archived.sort((a, b) => cmp([closedKey(b)], [closedKey(a)]));
  return [items, archived, [...problems, ...more]];
}

function closedKey(item: Item): string {
  return "closed" in item.meta ? str(item.meta.closed) : "";
}

/** The `*.md` files in a directory, sorted, as `sorted(directory.glob("*.md"))`. */
export function markdownFiles(directory: string): string[] {
  let names: string[];
  try {
    names = readdirSync(directory, { withFileTypes: true })
      .filter((e) => e.name.endsWith(".md") && !e.isDirectory())
      .map((e) => e.name);
  } catch {
    return [];
  }
  return names.sort((a, b) => cmp([a], [b])).map((n) => join(directory, n));
}

function loadDir(directory: string, archived: boolean): [Item[], Problem[]] {
  const items: Item[] = [];
  const problems: Problem[] = [];
  for (const path of markdownFiles(directory)) {
    try {
      items.push(parse(path, archived));
    } catch (exc) {
      if (!(exc instanceof FrontmatterError)) throw exc;
      problems.push(new Problem(path, "frontmatter", exc.reason));
    }
  }
  return [items, problems];
}
