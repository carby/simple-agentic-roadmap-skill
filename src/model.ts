export const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
export const FRONTMATTER = /^\+\+\+\n([\s\S]*?)\n\+\+\+\n?([\s\S]*)$/;

/** A command that cannot run as asked. It is reported as `error: ...` with exit status 2, as argparse does. */
export class UsageError extends Error {}

export class ConfigError extends UsageError {}

export class FrontmatterError extends Error {
  readonly path: string;
  readonly reason: string;

  constructor(path: string, reason: string) {
    super(`${path}: ${reason}`);
    this.path = path;
    this.reason = reason;
  }
}

export class Problem {
  readonly path: string;
  readonly rule: string;
  readonly message: string;
  readonly line: number | null;

  constructor(path: string, rule: string, message: string, line: number | null = null) {
    this.path = path;
    this.rule = rule;
    this.message = message;
    this.line = line;
  }

  /** What makes two problems the same one, as the frozen dataclass compares them. */
  get key(): string {
    return JSON.stringify([this.path, this.rule, this.message, this.line]);
  }

  toString(): string {
    const where = this.line ? `${this.path}:${this.line}` : this.path;
    return `${where}: ${this.message} [${this.rule}]`;
  }
}

/** A named point in time, declared in roadmap.toml. Items wait on one
 * through depends_on, or are due for one through `milestone`. */
export class Milestone {
  readonly id: string;
  readonly title: string;
  readonly date: Day;

  constructor(id: string, title: string, date: Day) {
    this.id = id;
    this.title = title;
    this.date = date;
  }

  toString(): string {
    return `${this.title} (${this.date})`;
  }
}

/** Where a roadmap lives and how its refs resolve. `root` is what refs are
 * relative to, which is the roadmap directory's parent unless roadmap.toml says
 * otherwise. */
export class Roadmap {
  readonly dir: string;
  readonly root: string;
  readonly refKinds: Map<string, readonly string[]>;
  readonly milestones: Map<string, Milestone>;

  constructor(dir: string, root: string, refKinds: Map<string, readonly string[]>, milestones = new Map()) {
    this.dir = dir;
    this.root = root;
    this.refKinds = refKinds;
    this.milestones = milestones;
  }

  get itemsDir(): string {
    return join(this.dir, "items");
  }

  get archiveDir(): string {
    return join(this.dir, "archive");
  }

  get readme(): string {
    return join(this.dir, "README.md");
  }

  get done(): string {
    return join(this.dir, "done.md");
  }

  get decisions(): string {
    return join(this.dir, "decisions.md");
  }
}

export type Meta = Record<string, unknown>;

export class Item {
  readonly path: string;
  readonly meta: Meta;
  readonly body: string;
  readonly archived: boolean;

  constructor(path: string, meta: Meta, body: string, archived = false) {
    this.path = path;
    this.meta = meta;
    this.body = body;
    this.archived = archived;
  }

  get id(): string {
    return "id" in this.meta ? str(this.meta.id) : stem(this.path);
  }

  get title(): string {
    return "title" in this.meta ? str(this.meta.title) : this.id;
  }

  get bucket(): string {
    return "bucket" in this.meta ? str(this.meta.bucket) : "";
  }

  get rank(): number {
    return isInt(this.meta.rank) ? this.meta.rank : 0;
  }
}

